        <h3>On-site field fabrication</h3>
        <p>GBI set up a dedicated fabrication yard at the brewery to build the tanks on site, then transported them to the cellars where they were installed. Crews cut, rolled, fit, welded, insulated, and clad every vessel.</p>
      </div>
      <div class="value-card">
        <div class="marker"></div>
        <h3>Full tank fleet across the brewery</h3>
        <p>GBI delivered fermenters, maturation (aging) tanks, and bright beer tanks across nine process areas &mdash; Area 2, 3, 7, 8 fermentation cellars; Area 4 and Area 9 maturation cellars; and the Area 6 bright beer cellar &mdash; in 2,000, 3,000, 5,000, and 7,000 BBL sizes.</p>
      </div>
      <div class="value-card">
        <div class="marker"></div>
        <h3>Built inside a live brewery</h3>
        <p>Installation was sequenced tightly to Molson Coors' production needs, with GBI setting tanks area-by-area and turning cellars over to the owner as they came online while adjacent construction continued.</p>
      </div>
      <div class="value-card">
        <div class="marker"></div>
        <h3>Food-grade precision</h3>
        <p>Every vessel was built to demanding ASME and food-and-beverage sanitary standards. Product-contact welds were dye-penetrant (PT) tested to a 100% defect-free acceptance, and surfaces were ground and polished to a hygienic Ra 0.3&ndash;0.6 &micro;m finish.</p>
