      <div class="cs-narrative">
        <p>Wet scrubbers are gas cleaning equipment where the dirty gas stream is brought into contact with a scrubbing liquid. The scrubber design depends on the industrial process conditions and the nature of the air pollutants involved. Wet scrubbers can be designed to collect particulates and/or gaseous pollutants by capturing particles in liquid droplets and by dissolving pollutant gases into the liquid.</p>
        <p>GBI was selected by Calaveras Power Partners L.P. (Zachry, Black &amp; Veatch and TIC) to help construct air pollution controls for CPS Energy's J.K. Spruce power plant, located in San Antonio, Texas.</p>
        <p>GBI constructed a 62&prime;&Oslash; &times; 155&prime; flue gas desulphurization wet scrubber for the new coal-fired 750 MW power unit #2. GBI also built and installed the adjacent elevated lime storage silo.</p>
        <p>GBI's welding expertise was critical to the success of the project and to ensure compliance with environmental regulations. The stack wall and spray headers were built of 317LMN stainless, and both the inlet and outlet ducts were constructed of C276 high-nickel alloy.</p>
